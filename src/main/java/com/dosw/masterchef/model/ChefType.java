package com.dosw.masterchef.model;

/**
 * Enumeration representing different types of chefs in the MasterChef Celebrity context.
 */
public enum ChefType {
    /**
     * viewer or audience member of the show
     */
    TELEVIDENTE,
    
    /**
     * Participant in the cooking competition
     */
    PARTICIPANTE,
    
    /**
     * Chef professional or judge on the show
     */
    CHEF_JURADO
}